import { Inject, Logger, Module, type OnModuleInit } from '@nestjs/common';
import { APP_ENV, type AppEnv } from '../../config/env';
import { WishesModule } from '../wishes/wishes.module';
import { GenerationService } from './generation.service';
import { FakeImageProvider } from './image/fake.image-provider';
import { IMAGE_PROVIDER, type ImageProvider } from './image/image-provider';
import { OpenAiImageProvider } from './image/openai.image-provider';
import { PosterPipelineService } from './poster-pipeline.service';
import { PosterQueue } from './poster.queue';
import { PostersController } from './posters.controller';
import { PostersService } from './posters.service';
import { PosterRateLimitService } from './rate-limit/poster-rate-limit.service';
import { ThemeCacheService } from './theme-cache.service';

/**
 * AI posters (FR-POS-01..13).
 *
 * `WishesModule` is imported for the ledger, the spend cap and the LLM provider — the three
 * things M5 built that M6 **extends rather than rebuilds**. In particular the spend cap is
 * cross-feature by design (§10 rule 6 caps the bill, not a feature), so a second one here
 * would let two features each sit under their own ceiling and together spend twice what
 * anybody intended.
 */
@Module({
  imports: [WishesModule],
  controllers: [PostersController],
  providers: [
    PostersService,
    PosterPipelineService,
    PosterQueue,
    GenerationService,
    ThemeCacheService,
    PosterRateLimitService,
    FakeImageProvider,
    {
      provide: IMAGE_PROVIDER,
      inject: [APP_ENV, FakeImageProvider],
      /**
       * Chosen by NAME, as every other provider in this app is, and `env.ts` has already
       * refused to boot if `openai` was named without a key.
       *
       * The stakes are higher here than for text. `gpt-image-1` bills per image, so a
       * deployment that silently went live would turn "try another" into ₹1–15 a tap.
       */
      useFactory: (env: AppEnv, fake: FakeImageProvider): ImageProvider => {
        switch (env.IMAGE_PROVIDER) {
          case 'openai':
            return new OpenAiImageProvider(
              env.OPENAI_API_KEY!,
              env.OPENAI_IMAGE_MODEL,
              env.OPENAI_IMAGE_QUALITY,
            );
          case 'fake':
          default:
            return fake;
        }
      },
    },
  ],
  exports: [ThemeCacheService],
})
export class PostersModule implements OnModuleInit {
  private readonly logger = new Logger(PostersModule.name);

  constructor(@Inject(APP_ENV) private readonly env: AppEnv) {}

  onModuleInit(): void {
    if (this.env.IMAGE_PROVIDER === 'fake') {
      this.logger.warn(
        'IMAGE_PROVIDER=fake. No background is generated by a model; every poster uses the ' +
          'pre-approved library, which is FR-POS-04’s main path and not a failure. ' +
          'Live generation is unavailable until OPENAI_API_KEY is set.',
      );
      return;
    }
    this.logger.log(
      `Poster backgrounds are live on ${this.env.OPENAI_IMAGE_MODEL} ` +
        `(quality=${this.env.OPENAI_IMAGE_QUALITY}). Every cache MISS now bills per image.`,
    );
  }
}
