import sharp from 'sharp';
import type { PosterFormat } from '@prisma/client';
import { FORMATS, type PosterTheme } from './theme-library';

/**
 * The background for the **common path** — the one that calls no model (FR-POS-04).
 *
 * `docs/BUILD_PROMPT_M6.md` is blunt about why this matters: "A milestone that treats live
 * generation as the main path has built the expensive version of the product and the one
 * that cannot work offline." So the library's artwork is rendered here, deterministically,
 * from the theme's own palette, and `gpt-image-1` is the premium edge.
 *
 * ## Why it is rendered rather than shipped as files
 *
 * Seven themes × three formats is 21 PNGs at up to 1080×1920. Committed to a public
 * repository they are a megabyte or two of binary that has to be regenerated by hand every
 * time TBD-5 moves a hex value, and `shipped-assets.spec.ts` already exists because the
 * Docker image copies `prisma`, `src`, `tsconfig*` and `nest-cli.json` and nothing else —
 * so a `docs/` or `assets/` read at runtime is a production crash, which the first version
 * of `theme-library.ts` committed and this test now prevents.
 *
 * Rendering from the manifest means the artwork cannot drift from the theme it belongs to,
 * and when TBD-5 lands the change is the palette rather than 21 files.
 *
 * **What it gives up:** a gradient is not art. These are visibly placeholders and the
 * display names say so. FR-POS-04's "hand-approved" names a hand that is not a session's.
 * When real artwork arrives it goes through `theme_cache` like generated artwork does —
 * same key, same lookup — so this function becomes the fallback rather than the path.
 *
 * ## It is still cached, and that is the point of definition-of-done item 5
 *
 * The result goes into `theme_cache` on first use, so the SECOND request for the same key
 * does not re-render: it reads bytes. That makes the cache hit a real, measurable thing
 * rather than a branch that happens to be fast, and it means the hit path is identical
 * whether the artwork was generated by a model or by this file.
 */
export async function renderLibraryArtwork(
  theme: PosterTheme,
  format: PosterFormat,
): Promise<Buffer> {
  const { width, height } = FORMATS[format];

  /**
   * A diagonal gradient plus a soft radial wash, and nothing else.
   *
   * No motifs are drawn, deliberately, even though the theme names some. A balloon drawn by
   * this function would be a balloon drawn from a list that `BANNED_ON_SOLEMN` filters by
   * NAME — and the first time somebody added "candle" to a celebratory theme's motifs and a
   * solemn theme's, the filter would be protecting a string while the renderer drew the
   * shape. The motifs are for the art prompt, where a model reads them, and for the
   * fixture's banned-word check. Nothing in the committed path renders them.
   */
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${theme.background.from}"/>
      <stop offset="100%" stop-color="${theme.background.to}"/>
    </linearGradient>
    <radialGradient id="wash" cx="50%" cy="35%" r="70%">
      <stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.18"/>
      <stop offset="100%" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${width}" height="${height}" fill="url(#bg)"/>
  <rect width="${width}" height="${height}" fill="url(#wash)"/>
</svg>`;

  return sharp(Buffer.from(svg)).png().toBuffer();
}
