import { z } from 'zod';
import { assertValidSpec, InvalidEventDateError } from '../../common/date/occurrence';
import { ALLOWED_EVENT_TYPES } from '../events/event-rules';

/**
 * DERIVED fields. A client may not send any of these: `sentiment` is computed from the event
 * type and whether the person is deceased, `isMinor` from a known birth year,
 * `completenessScore` from the profile, and `milestoneLabel` from the elapsed years.
 *
 * Every write schema below is `.strict()`, so one of these arriving is a 400 that names the
 * field. docs/BUILD_PROMPT_M1.md is explicit that a client posting sentiment=CELEBRATORY
 * with type=DEATH_ANNIVERSARY must be REJECTED, not honoured — and silently stripping it,
 * which a non-strict object does, is neither.
 */
export const SERVER_DERIVED_FIELDS = [
  'sentiment',
  'isMinor',
  'completenessScore',
  'milestoneLabel',
] as const;

/**
 * Ids are generated by the CLIENT, not the server.
 *
 * Offline-first means a person exists and has an identity before the network has ever seen
 * them (D23). If the server minted ids, every offline record would need rewriting on first
 * sync, and every local reference to it would have to be chased down.
 */
export const UuidSchema = z
  .string()
  .regex(
    /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/,
    'must be a UUID',
  );

/** Day/month are always known; year is nullable because "year unknown" is first-class. */
export const EventDateSchema = z.object({
  day: z.number().int().min(1).max(31),
  month: z.number().int().min(1).max(12),
  year: z.number().int().min(1900).max(2200).nullable().optional(),
});

/**
 * Rejects dates that do not exist (31 April, 29 Feb 2023) while allowing 29 Feb with an
 * unknown year, which is a real birthday and must survive to the leap-day rule in
 * `occursOnIn`.
 */
export function refineEventDate(
  value: { day: number; month: number; year?: number | null },
  ctx: z.RefinementCtx,
): void {
  try {
    assertValidSpec({ day: value.day, month: value.month, year: value.year ?? null });
  } catch (cause) {
    ctx.addIssue({
      code: 'custom',
      message: cause instanceof InvalidEventDateError ? cause.message : 'invalid date',
      path: ['day'],
    });
  }
}

const IsoInstant = z.string().datetime({ offset: true });

const OptionalText = (max: number) => z.string().trim().max(max).nullable().optional();

export const PersonUpsertSchema = z
  .object({
    id: UuidSchema,
    displayName: z.string().trim().min(1).max(120),
    relationToOwner: OptionalText(60),
    isSelf: z.boolean().optional(),

    // M1 profile fields (FR-PPL-04). All optional, all free text.
    gender: OptionalText(40),
    phone: OptionalText(40),
    email: OptionalText(254),
    notes: OptionalText(2000),

    /**
     * Directly settable (FR-PPL-04 lists a deceased flag as a profile field), unlike the
     * other three derived values. Creating a DEATH_ANNIVERSARY also forces it true, and the
     * server will not let a client clear it while one is still live.
     */
    isDeceased: z.boolean().optional(),

    /** The client's clock for this record. Drives last-write-wins. */
    updatedAt: IsoInstant,
    /** Soft delete: a tombstone is an upsert with this set (D23). */
    deletedAt: IsoInstant.nullable().optional(),
  })
  .strict();

export const EventTypeSchema = z.enum(ALLOWED_EVENT_TYPES);

export const EventUpsertSchema = z
  .object({
    id: UuidSchema,
    personId: UuidSchema,
    /** All five types in M1 (FR-EVT-01). M0 accepted BIRTHDAY only. */
    type: EventTypeSchema.default('BIRTHDAY'),
    ...EventDateSchema.shape,
    /** CUSTOM only (FR-EVT-06). Rejected on any other type — see below. */
    label: z.string().trim().min(1).max(60).nullable().optional(),
    /** Stops reminders without deleting the event. */
    isMuted: z.boolean().optional(),
    updatedAt: IsoInstant,
    deletedAt: IsoInstant.nullable().optional(),
  })
  .strict()
  .superRefine(refineEventDate)
  .superRefine(refineEventLabel);

/**
 * A label belongs to a CUSTOM event and nowhere else (FR-EVT-06).
 *
 * Rejected rather than ignored: a client that thinks it is naming a birthday has a bug, and
 * accepting the write would hide it until someone wondered why the name never appeared.
 */
export function refineEventLabel(
  value: { type?: string; label?: string | null | undefined },
  ctx: z.RefinementCtx,
): void {
  const type = value.type ?? 'BIRTHDAY';
  if (type === 'CUSTOM') {
    if (!value.label || !value.label.trim()) {
      ctx.addIssue({
        code: 'custom',
        message: 'a CUSTOM event needs a label — it has no other name',
        path: ['label'],
      });
    }
    return;
  }
  if (value.label != null) {
    ctx.addIssue({
      code: 'custom',
      message: `label is only valid on a CUSTOM event, not ${type}`,
      path: ['label'],
    });
  }
}

/** Traits sync like everything else, tombstones included. */
export const TraitUpsertSchema = z
  .object({
    id: UuidSchema,
    personId: UuidSchema,
    kind: z.enum(['HOBBY', 'LIKE', 'DISLIKE', 'BUDGET_BAND']),
    value: z.string().trim().min(1).max(120),
    updatedAt: IsoInstant,
    deletedAt: IsoInstant.nullable().optional(),
    // `source` is deliberately absent: M1 only ever writes USER, and letting a client claim
    // a trait was INFERRED would let it launder a guess into something shown as fact.
  })
  .strict();

export const SyncPushSchema = z
  .object({
    people: z.array(PersonUpsertSchema).max(500).default([]),
    events: z.array(EventUpsertSchema).max(500).default([]),
    traits: z.array(TraitUpsertSchema).max(500).default([]),
  })
  .strict();

export const SyncPullQuerySchema = z.object({
  cursor: z.string().min(1).optional(),
  limit: z.coerce.number().int().min(1).max(500).default(200),
});

export type PersonUpsert = z.infer<typeof PersonUpsertSchema>;
export type EventUpsert = z.infer<typeof EventUpsertSchema>;
export type TraitUpsert = z.infer<typeof TraitUpsertSchema>;
export type SyncPush = z.infer<typeof SyncPushSchema>;
