package `in`.wishkaro.app.platform

import android.app.Activity
import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import `in`.wishkaro.app.R

/**
 * Google Sign-In through Credential Manager (FR-AUTH-02).
 *
 * `default_web_client_id` is generated by the google-services plugin from the WEB OAuth
 * client in google-services.json — the same client the server validates ID tokens against.
 * Using the Android client id here fails every request with an error that does not say why.
 */
class AndroidGoogleSignInClient(
    private val appContext: Context,
    private val activityProvider: () -> Activity?,
) : GoogleSignInClient {

    override suspend fun signIn(): GoogleSignInResult {
        val activity = activityProvider()
            ?: return GoogleSignInResult.Failure("No activity in the foreground")

        val serverClientId = appContext.getString(R.string.default_web_client_id)
        val manager = CredentialManager.create(activity)

        // First try the quiet path: accounts already authorised on this device. If there are
        // none — a fresh install, or the user has never signed in — fall back to the explicit
        // "Sign in with Google" sheet, which also offers adding an account.
        return attempt(manager, activity, authorizedOnly = true, serverClientId)
            ?: attempt(manager, activity, authorizedOnly = false, serverClientId)
            ?: GoogleSignInResult.Failure("No Google account available on this device")
    }

    private suspend fun attempt(
        manager: CredentialManager,
        activity: Activity,
        authorizedOnly: Boolean,
        serverClientId: String,
    ): GoogleSignInResult? {
        val option = if (authorizedOnly) {
            GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(true)
                .setServerClientId(serverClientId)
                .setAutoSelectEnabled(false)
                .build()
        } else {
            GetSignInWithGoogleOption.Builder(serverClientId).build()
        }

        return try {
            val response = manager.getCredential(
                activity,
                GetCredentialRequest.Builder().addCredentialOption(option).build(),
            )
            val credential = response.credential
            if (
                credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                GoogleSignInResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleSignInResult.Failure("Unexpected credential type: ${credential.type}")
            }
        } catch (_: GetCredentialCancellationException) {
            GoogleSignInResult.Cancelled
        } catch (_: NoCredentialException) {
            // Signals "try the other option", not a failure.
            null
        } catch (e: GetCredentialException) {
            Log.w(TAG, "Credential Manager failed (authorizedOnly=$authorizedOnly)", e)
            if (authorizedOnly) null else GoogleSignInResult.Failure(e.message ?: "Sign-in failed")
        }
    }

    private companion object {
        const val TAG = "GoogleSignIn"
    }
}
